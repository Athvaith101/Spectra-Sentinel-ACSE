export class RFSimulator {
  public currentTimeMs: number = 0;
  public channelCount: number = TOTAL_CHANNELS;
  public emitters: EmitterDefinition[] = [];
  public reactiveManager: ReactiveEmitterManager = new ReactiveEmitterManager();

  private lastEmitTime: Map<string, number> = new Map();
  private nextPulseId = { val: 1 };

  constructor(scenario?: BenchmarkScenario, seed?: number) {
    if (scenario) {
      this.loadScenario(scenario, seed);
    } else {
      this.loadDefaultScenario();
    }
  }

  public loadScenario(scenario: BenchmarkScenario, seed?: number): void {
    this.currentTimeMs = 0;
    this.channelCount = scenario.channelCount || TOTAL_CHANNELS;
    this.emitters = JSON.parse(JSON.stringify(scenario.emitters));
    this.lastEmitTime.clear();
    this.nextPulseId.val = 1;
    this.reactiveManager.reset(seed !== undefined ? seed + 7001 : undefined);

    for (let i = 0; i < this.emitters.length; i++) {
      const em = this.emitters[i];
      if (seed !== undefined) {
        // Seed-based phase shift of initial hopping index and PRI offset
        const pseudoRand = ((seed * (i + 1) * 9301 + 49297) % 233280) / 233280;
        em.currentHopIndex = Math.floor(pseudoRand * em.hoppingSequence.length);
      }
      this.lastEmitTime.set(em.id, 0);
      if (em.type === 'burst_lpi') {
        em.isBurstActive = true;
      }
    }
  }

  public loadDefaultScenario(): void {
    this.loadScenario(DEFAULT_SCENARIOS[0]);
  }

  /**
   * Advances the RF environment by dtMs and returns all ground truth pulses generated
   */
  public step(dtMs: number): GroundTruthPulse[] {
    const startMs = this.currentTimeMs;
    const endMs = startMs + dtMs;
    this.currentTimeMs = endMs;
    const pulses: GroundTruthPulse[] = [];

    for (const em of this.emitters) {
      const lastT = this.lastEmitTime.get(em.id) || 0;
      const { pulses: emPulses, updatedLastEmitTime } = EmitterPhysics.generatePulses(
        em,
        startMs,
        endMs,
        lastT,
        this.nextPulseId
      );
      this.lastEmitTime.set(em.id, updatedLastEmitTime);
      for (const p of emPulses) {
        pulses.push(p);
      }
    }

    // Incorporate any decoy pulses generated by reactive emitters
    const decoys = this.reactiveManager.drainDecoyPulses();
    for (const d of decoys) {
      pulses.push(d);
    }

    return pulses;
  }

  public registerIntercept(emitterId: string): boolean {
    const res = this.reactiveManager.registerIntercept(emitterId, this.currentTimeMs, this.emitters);
    return res.adapted;
  }

  public forceReactiveTactic(tactic: ReactiveEvasionType): void {
    this.reactiveManager.forceTactic(tactic, this.emitters, this.currentTimeMs);
  }

  public triggerAdversarialShift(): void {
    for (const em of this.emitters) {
      if (em.type === 'adversarial_shift') {
        em.hoppingSequence = em.hoppingSequence.map((ch) => (ch + 11) % this.channelCount);
      }
    }
  }

  public injectNovelEmitter(): void {
    const novelId = `novel-${Date.now()}`;
    const novelEmitter: EmitterDefinition = {
      id: novelId,
      name: 'UNKNOWN X-BAND AGILE RADAR',
      type: 'novel_unseen',
      baseFreqMHz: BASE_FREQ_MHZ,
      channelSpan: 8,
      hoppingSequence: [26, 17, 29, 13, 24, 18],
      currentHopIndex: 0,
      priMs: 0.8,
      pulseWidthUs: 1.5,
      powerDbm: -15,
      priority: 5,
      snrDb: 22,
    };
    this.emitters.push(novelEmitter);
    this.lastEmitTime.set(novelId, this.currentTimeMs);
  }
}

