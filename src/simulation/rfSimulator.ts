export function getMissionModeForScenario(scenarioIndex: number): ScenarioMissionMode {
  switch (scenarioIndex) {
    case 0:
      return 'dense_agile';
    case 1:
      return 'sparse_asynchronous';
    case 2:
      return 'general_surveillance';
    case 3:
      return 'high_threat_alert';
    case 4:
      return 'adversarial_ood';
    case 5:
      return 'dense_agile';
    case 6:
      return 'high_threat_alert';
    default:
      return 'general_surveillance';
  }
}

